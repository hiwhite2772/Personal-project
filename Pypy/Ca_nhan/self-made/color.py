class Colors:
    RED = '\033[91m'
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    BLUE = '\033[94m'
    PURPLE = '\033[95m'
    CYAN = '\033[96m'
    WHITE = '\033[97m'
    END = '\033[0m'

print(f"{Colors.RED} Canh bao: Loi quan trong! {Colors.END}")
print(f"{Colors.GREEN} Thanh cong, xin cam on! {Colors.END}")
print(f"{Colors.CYAN} Vui long den cho noi an toan! {Colors.END}")
print(f"{Colors.WHITE} Thong bao: Vui long di chuyen ngay! {Colors.END}")
print(f"{Colors.BLUE} Hay den dia diem lon nhat! {Colors.END}")
print(f"{Colors.YELLOW} Vui long khong duoc su dung dien thoai! {Colors.END}")
print(f"{Colors.PURPLE} Hay dien vao phieu thong tin! {Colors.END}")